// Common REST error DTO (PLAN 2.3): { error: { code, message, details? } } + HTTP status.
import { z } from 'zod';

export const ApiErrorCode = z.enum([
  'validation', // 400
  'unauthorized', // 401 missing/wrong X-SP-Token (also after a server restart: the token rotates)
  'forbidden', // 403 Host / Origin / Sec-Fetch-Site / OPTIONS
  'not_found', // 404
  'conflict', // 409
  'context_not_ready', // 409 AI task before the paper is context_ready
  'payload_too_large', // 413
  'unsupported_media_type', // 415 body with a Content-Type other than application/json (upload: application/pdf)
  'internal', // 500
  'not_implemented', // 501 route registered but not implemented yet
  'reference_search_unavailable', // 503 reference metadata search disabled or temporarily unavailable
]);
export type ApiErrorCode = z.infer<typeof ApiErrorCode>;

export const API_ERROR_STATUS: Record<ApiErrorCode, number> = {
  validation: 400,
  unauthorized: 401,
  forbidden: 403,
  not_found: 404,
  conflict: 409,
  context_not_ready: 409,
  payload_too_large: 413,
  unsupported_media_type: 415,
  internal: 500,
  not_implemented: 501,
  reference_search_unavailable: 503,
};

export const ErrorDtoSchema = z.object({
  error: z.object({
    code: ApiErrorCode,
    message: z.string(),
    details: z.unknown().optional(),
  }),
});
export type ErrorDto = z.infer<typeof ErrorDtoSchema>;

/**
 * The contract of `error.details` on a 409 `conflict` (PLAN_M2 D22). One place for every reason:
 * - payload_version (M1.2): the request id belongs to a row stored by an older server version; never attached.
 * - card_generating (M2): a card of this kind is being generated by `runId` (card `cardId`) and a NEW request id
 *   arrived — the client polls llm.runs.get(runId) instead of starting another run.
 */
export const ConflictDetails = z.discriminatedUnion('reason', [
  z.object({ reason: z.literal('payload_version'), runId: z.string().min(1) }),
  z.object({ reason: z.literal('card_generating'), runId: z.string().min(1), cardId: z.string().min(1) }),
]);
export type ConflictDetails = z.infer<typeof ConflictDetails>;

/** The typed details of a 409, or null when absent or not one of the ConflictDetails forms. */
export function parseConflictDetails(details: unknown): ConflictDetails | null {
  const r = ConflictDetails.safeParse(details);
  return r.success ? r.data : null;
}

export function errorDto(code: ApiErrorCode, message: string, details?: unknown): ErrorDto {
  return details === undefined ? { error: { code, message } } : { error: { code, message, details } };
}
